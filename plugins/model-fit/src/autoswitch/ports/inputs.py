from typing import Any, Protocol


class Inputs(Protocol):
    def prompt_digest(self, prompt: str) -> str: ...

    def input_digest(self, content: list[dict[str, Any]]) -> str: ...

    def input_text(self, content: list[dict[str, Any]]) -> str: ...

    def hook_prompt(self, content: list[dict[str, Any]]) -> str: ...
