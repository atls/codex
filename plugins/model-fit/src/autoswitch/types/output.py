from model_fit.assessment.types.decision import AssessmentDecision
from model_fit.autoswitch.recommendation.types.evidence import RecommendationEvidence
from typing import Any, Protocol


class HookOutputRenderer(Protocol):
    control_prompt: str
    control_prompts: tuple[str, ...]
    replay_context: str
    handoff_cancelled_context: str
    replay_stop_reason: str

    def queued_context(self) -> dict[str, Any]: ...

    def pending_context(self) -> dict[str, Any]: ...

    def hook_output(
        self, result: AssessmentDecision | RecommendationEvidence
    ) -> dict[str, Any] | None: ...

    def allow_tool(self, updated_input: dict[str, Any]) -> dict[str, Any]: ...

    def deny_tool(self, reason: str) -> dict[str, Any]: ...

    def block(self, reason: str) -> dict[str, Any]: ...

    def warning(self, message: str) -> dict[str, Any]: ...

    def unknown(self, message: str | None = None) -> dict[str, Any]: ...

    def context(self, context: str) -> dict[str, Any]: ...

    def with_context(
        self, output: dict[str, Any] | None, context: str
    ) -> dict[str, Any]: ...

    def extend_reason(self, output: dict[str, Any], text: str) -> None: ...

    def is_block(self, output: dict[str, Any]) -> bool: ...

    def control_context(
        self, thread_id: str, turn_id: str, state: dict[str, Any]
    ) -> dict[str, Any]: ...

    def queue_command(self, thread_id: str, turn_id: str) -> str: ...

    def assessed(self) -> dict[str, Any]: ...

    def prompt_outcome(self, output: dict[str, Any] | None) -> str: ...
