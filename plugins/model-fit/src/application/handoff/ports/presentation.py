from typing import Any, Protocol


class Presentation(Protocol):
    control_prompt: str
    replay_context: str
    handoff_cancelled_context: str
    replay_stop_reason: str

    def queued_context(self) -> Any: ...
    def pending_context(self) -> Any: ...
    def hook_output(self, result: dict[str, Any]) -> Any: ...
    def allow_tool(self, updated_input: dict[str, Any]) -> Any: ...
    def deny_tool(self, reason: str) -> Any: ...
    def block(self, reason: str) -> Any: ...
    def warning(self, message: str) -> Any: ...
    def unknown(self, message: str | None = None) -> Any: ...
    def context(self, context: str) -> Any: ...
    def with_context(self, output: Any, context: str) -> Any: ...
    def extend_reason(self, output: Any, text: str) -> None: ...
    def is_block(self, output: Any) -> bool: ...
    def control_context(
        self, thread_id: str, turn_id: str, state: dict[str, Any]
    ) -> Any: ...
    def queue_command(self, thread_id: str, turn_id: str) -> str: ...
    def assessed(self) -> dict[str, Any]: ...
    def prompt_outcome(self, output: dict[str, Any] | None) -> str: ...
