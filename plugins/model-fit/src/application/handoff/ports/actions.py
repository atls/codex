from typing import Any, Protocol

from ..requests.tool_check import ToolCheck


class Actions(Protocol):
    def matches_assessment(self, request: ToolCheck) -> bool: ...
    def bound_transfer_input(
        self, request: ToolCheck, state: dict[str, Any]
    ) -> dict[str, Any] | None: ...
    def matches_profile_switch(
        self, request: ToolCheck, state: dict[str, Any]
    ) -> bool: ...
    def matches_queue(self, request: ToolCheck, state: dict[str, Any]) -> bool: ...
    def matches_transfer(self, request: ToolCheck) -> bool: ...
